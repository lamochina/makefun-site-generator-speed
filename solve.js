// byte, in less CPU time. Dependency-free ES module. The semantics are makefun-site's own (its vendor code is the
// reference); the hot paths (inline Markdown, HTML escaping, slugs, template rendering) are rewritten around bulk
// string operations instead of per-character work. Nothing is cached from one case (one run call) to the next: every
